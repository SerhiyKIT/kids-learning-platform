#!/usr/bin/env bash
#
# Creates the handoff backlog (labels + milestones + issues) in
# SerhiyKIT/kids-learning-platform.
#
# Run it in a terminal where GitHub CLI is logged in AS THE REPO OWNER:
#   gh auth status          # must show you are logged in with repo scope
#   bash create-github-issues.sh
#
# It is IDEMPOTENT: labels/milestones/issues that already exist (by name/title)
# are skipped, so it is safe to re-run.
#
set -euo pipefail

REPO="SerhiyKIT/kids-learning-platform"

command -v gh >/dev/null || { echo "ERROR: GitHub CLI (gh) not found. Install: https://cli.github.com/"; exit 1; }
gh auth status >/dev/null 2>&1 || { echo "ERROR: not logged in. Run: gh auth login"; exit 1; }
echo ">> Target repo: $REPO"

# ---------------------------------------------------------------------------
# Labels (idempotent)
# ---------------------------------------------------------------------------
mklabel() { # name color description
  if gh label list -R "$REPO" --limit 200 --json name -q '.[].name' | grep -qxF "$1"; then
    echo "   label exists: $1"
  else
    gh label create "$1" -R "$REPO" --color "$2" --description "$3" >/dev/null && echo "   label created: $1"
  fi
}
echo ">> Labels"
mklabel "epic"            "5319e7" "Парасолькова задача, що об'єднує менші"
mklabel "area:backend"   "1d76db" "Spring Boot / Java"
mklabel "area:frontend"  "0e8a16" "Next.js / TypeScript"
mklabel "area:ai"        "d93f0b" "LLM / TTS / генерація контенту"
mklabel "area:security"  "b60205" "Безпека та приватність дитячих даних"
mklabel "area:devops"    "0052cc" "Деплой, CI/CD, інфраструктура"
mklabel "area:content"   "fbca04" "Навчальний контент та ассети"
mklabel "area:qa"        "c2e0c6" "Тестування, доступність, якість"
mklabel "priority:high"  "d93f0b" "Робити першочергово"
mklabel "priority:medium" "fbca04" "Середній пріоритет"
mklabel "priority:low"   "0e8a16" "Можна відкласти"

# ---------------------------------------------------------------------------
# Milestones (idempotent, via REST)
# ---------------------------------------------------------------------------
mkmilestone() { # title description
  if gh api "repos/$REPO/milestones?state=all&per_page=100" -q '.[].title' | grep -qxF "$1"; then
    echo "   milestone exists: $1"
  else
    gh api "repos/$REPO/milestones" -f title="$1" -f description="$2" >/dev/null && echo "   milestone created: $1"
  fi
}
echo ">> Milestones"
mkmilestone "M1 — Реальні AI-провайдери"      "Заміна stub-провайдерів LLM та TTS на реальні."
mkmilestone "M2 — Адмін та модерація (UI)"    "Веб-екрани для 2FA адміністратора, модерації та керування вчителями."
mkmilestone "M3 — Дитячий досвід"             "Полірування дитячого режиму та вибір стилю дитиною з ШІ-оформленням."
mkmilestone "M4 — Навчальний контент"         "Ассети та навчальні модулі: математика, логіка, читання, письмо."
mkmilestone "M5 — Production-готовність"       "Деплой, hardening, provisioning вчителів, приватність."
mkmilestone "M6 — Якість"                     "E2E-тести, доступність та i18n."

# ---------------------------------------------------------------------------
# Shared footer appended to every issue body
# ---------------------------------------------------------------------------
FOOTER=$(cat <<'EOF'

---
### Робочий процес
- **STEP 0** перед роботою: `git checkout main && git pull --ff-only`, потім `docker compose -f infra/docker-compose.yml up -d`.
- Гілка `feat/<name>`; локально `cd backend && ./mvnw test` до пушу; для фронта `npm run lint && npm run build`.
- **Готово = зелений чекмарк GitHub Actions.** Виправляти корінь, не маскувати (без вимкнених тестів / `eslint-disable`).
- Дотримуватися `docs/CONVENTIONS.md`. Пояснення/PR — українською; код/коміти/коментарі — англійською.

### Обмеження безпеки (діють завжди)
- Жодних секретів у коді — усе через env. Жодних дефолтних паролів адміна.
- Приватність дитячих даних: 404-не-403 за власником; без PII батьків у відповідях вчителю; каскад для «права бути забутим»; `audit_log` не каскадиться.
- Dev-ендпоінти (`seed-demo`, `register-role`) лишаються `@Profile("dev")` і прибираються перед продакшеном.
- Зовнішні провайдери — за інтерфейсами зі stub-реалізаціями, щоб CI не потребував реальних API чи MinIO.
- ШІ-контент (уроки, дитячі стилі) — лише через модерацію перед показом дитині.
EOF
)

# ---------------------------------------------------------------------------
# Issue creator (idempotent by exact title)
# ---------------------------------------------------------------------------
EXISTING_TITLES="$(gh issue list -R "$REPO" --state all --limit 300 --json title -q '.[].title')"
mkissue() { # title milestone labels body
  local title="$1" milestone="$2" labels="$3" body="$4"
  if grep -qxF "$title" <<<"$EXISTING_TITLES"; then
    echo "   issue exists: $title"
    return
  fi
  local tmp; tmp="$(mktemp)"
  printf '%s\n%s\n' "$body" "$FOOTER" > "$tmp"
  gh issue create -R "$REPO" --title "$title" --milestone "$milestone" --label "$labels" --body-file "$tmp" >/dev/null \
    && echo "   issue created: $title"
  rm -f "$tmp"
}
echo ">> Issues"

